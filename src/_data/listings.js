/* Business directory.

   A curated directory of Niwot businesses, checked against business-owned
   and community sources: each business's own website where it publishes
   one, the Niwot Business Association's directory at niwot.com, and dated
   reports in the Left Hand Valley Courier (lhvc.com). Nothing here is
   inferred — a field is present only where a source stated it.

   The record shape, the validation rules and the freshness threshold are
   documented in lib/directory.js. The short version:

   - `verifiedAt` is the day that particular row was last checked, and the
     page shows it row by row. The rows dated 2026-09-08 were compiled on the
     first pass; the rows dated 2026-09-09 were re-checked or added in the
     September 2026 audit.
   - `status` decides what is published. Only `active` and
     `temporarily_closed` rows render. `closed` and `unverified` rows stay
     here as the record of what was checked and why, with an `editorialNote`
     that is never published.
   - `address` is the street address as published, with suite numbers only
     where a single source gives them unambiguously. `sharesAddress: true`
     marks an address knowingly shared with another row — a counter inside
     Niwot Market, two suites in one building — so the duplicate-address
     check can tell that from one business replacing another.
   - Phone numbers are deliberately not reproduced. They change more often
     than anything else on a listing, so every row links out instead.
   - `description` is omitted where no source described the business. A row
     with a name, a category and a place is still a useful row; an invented
     sentence is not.

   Closures recorded in earlier passes and dropped rather than archived:
   Bell, Book, Candle & Coffee (lease ended May 2018), The Wandering
   Jellyfish Bookshop (December 2023), Farow (2025), Few of a Kind Vintage +
   Mercantile (April 25, 2026), Pie Dog Pizza, The Little Shop and Niwot
   Veterinary Clinic. Lefty's Gourmet Pizza left 364 Second Avenue for
   Longmont and trades there as Niwot Pizza.

   Coverage is not a claim of completeness. The Association directory was
   searched rather than crawled end to end, and a sole trader who keeps no
   public listing will not appear. The page says so and invites the ones that
   are missing. */
